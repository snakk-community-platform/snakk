// Generates Scripts/data/lang-icons.ts from simple-icons.
// Run via: node gen-lang-icons.mjs

import { writeFile, mkdir } from 'fs/promises';
import { existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname } from 'path';
import * as si from 'simple-icons';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Mapping: code modal language value → simple-icons key(s) to try in order
const LANG_ICONS = {
    javascript: ['siJavascript'],
    typescript: ['siTypescript'],
    csharp:     ['siCsharp', 'siDotnet'],
    html:       ['siHtml5', 'siHtml'],
    css:        ['siCss3', 'siCss'],
    bash:       ['siGnubash', 'siBash'],
    python:     ['siPython'],
    markdown:   ['siMarkdown'],
    cpp:        ['siCplusplus', 'siCpp'],
    java:       ['siJava', 'siOpenjdk'],
    lua:        ['siLua'],
    perl:       ['siPerl'],
    php:        ['siPhp'],
    powershell: ['siPowershell', 'siPowershellcore', 'siGnuwindows'],
    r:          ['siR'],
    ruby:       ['siRuby'],
    rust:       ['siRust'],
};

const entries = {};

for (const [langKey, siKeys] of Object.entries(LANG_ICONS)) {
    let found = false;
    for (const siKey of siKeys) {
        const icon = si[siKey];
        if (icon) {
            entries[langKey] = {
                inner: `<path d="${icon.path}"/>`,
                hex: icon.hex,
                viewBox: '0 0 24 24'
            };
            found = true;
            break;
        }
    }
    if (!found) {
        console.warn(`gen-lang-icons: no SI icon found for ${langKey} (tried: ${siKeys.join(', ')})`);
    }
}

const dataDir = './Scripts/data';
if (!existsSync(dataDir)) await mkdir(dataDir, { recursive: true });

const lines = Object.entries(entries)
    .map(([k, v]) => `    ${JSON.stringify(k)}: { inner: ${JSON.stringify(v.inner)}, hex: ${JSON.stringify(v.hex)}, viewBox: ${JSON.stringify(v.viewBox)} }`);

const output =
`// <auto-generated> by gen-lang-icons.mjs — do not edit manually
(function () {
    (window as any).snakkLangIcons = {
${lines.join(',\n')}
    };
})();
`;

await writeFile(`${dataDir}/lang-icons.ts`, output, 'utf-8');
console.log(`gen-lang-icons: generated lang-icons.ts (${Object.keys(entries).length} icons)`);
